/**
 * Module registry (EVOL-P2-001) — the single source of truth for module
 * identity across the API and the web app.
 *
 * Each entry carries the module `key` (matches `permissions.module_key`,
 * navigation `module` fields, and `client_portal_entitlements.module_key`),
 * its display `name`, a lucide-react `icon` name, the `permissions` seeded
 * for it by migration 5302118, the known UI `routes`, and — for the
 * client-portal modules — the `entitlement` tier it belongs to.
 *
 * Consumers:
 *  - `apps/api/src/lib/entitlements.ts` derives the default/subscription
 *    module sets from the `entitlement` tiers.
 *  - `apps/web/lib/permissions.ts` derives `MODULE_LABELS` from `name`.
 *  - `apps/web/app/(admin)/admin/client-portal/ClientPortalEntitlementsForm.tsx`
 *    derives its portal-module list from the same tiers.
 *
 * Drift guards (see `apps/api/src/__tests__/module-registry.test.ts` and
 * `apps/web/__tests__/lib/module-registry.test.ts`): the permission catalog
 * migration, the portal/admin nav catalogs, and the entitlement sets are
 * asserted against this registry, so adding or renaming a module without
 * updating the registry fails CI.
 *
 * Scope note (incremental): this covers every module referenced by the
 * permission catalog, nav catalogs, and entitlement lists today. The
 * remaining consumers named in EVOL-P2-001 (API mount table, SDK sub-APIs)
 * still hand-wire their own lists and can migrate to this registry next;
 * the registry is deliberately dependency-free so every app can import it.
 */
export interface ModuleDefinition {
  /** Module key: `permissions.module_key`, nav `module`, entitlement `module_key`. */
  key: string;
  /** Display name shown in navigation and the permission matrix. */
  name: string;
  /** lucide-react icon name (PascalCase, as exposed by the `icons` export). */
  icon: string;
  /** `module:action` permission keys seeded by migration 5302118. */
  permissions: string[];
  /** Known UI routes per surface. */
  routes?: { portal?: string[]; admin?: string[] };
  /** Client-portal entitlement tier; unset = not a client-portal module. */
  entitlement?: "default" | "subscription";
}

