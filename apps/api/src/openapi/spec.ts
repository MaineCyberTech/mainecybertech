// Ticket rows have ~20 columns; the schema documents the key fields and leaves
// the rest open (`additionalProperties: true`) so response drift stays visible
// without turning every new column into a spec break.
const ticketRowProperties: Record<string, unknown> = {
  id: { type: "string" },
  organization_id: { type: "string" },
  title: { type: "string" },
  description: { type: "string", nullable: true },
  status: {
    type: "string",
    enum: ["new", "triaged", "in_progress", "waiting_on_client", "resolved", "closed"],
  },
  priority: { type: "string", enum: ["low", "normal", "high", "urgent"] },
  category: { type: "string", nullable: true },
  source: { type: "string" },
  assigned_to: { type: "string", nullable: true },
  external_jsm_issue_key: { type: "string", nullable: true },
  jira_last_synced_at: { type: "string", nullable: true },
  labels: { type: "array", items: { type: "string" }, nullable: true },
  resolution: { type: "string", nullable: true },
  metadata: { nullable: true },
  version: { type: "number" },
  created_at: { type: "string" },
  updated_at: { type: "string" },
};

const ticketRequired = [
  "id",
  "organization_id",
  "title",
  "status",
  "priority",
  "source",
  "created_by",
  "created_at",
  "updated_at",
  "version",
];

const ticketRowSchema: Record<string, unknown> = {
  type: "object",
  additionalProperties: true,
  required: ticketRequired,
  properties: { ...ticketRowProperties, created_by: { type: "string" } },
};

const ticketCommentSchema: Record<string, unknown> = {
  type: "object",
  additionalProperties: true,
  required: [
    "id",
    "ticket_id",
    "organization_id",
    "author_id",
    "body",
    "is_internal",
    "created_at",
  ],
  properties: {
    id: { type: "string" },
    ticket_id: { type: "string" },
    organization_id: { type: "string" },
    author_id: { type: "string" },
    body: { type: "string" },
    is_internal: { type: "boolean" },
    created_at: { type: "string" },
    edited_at: { type: "string", nullable: true },
  },
};

const ticketDetailSchema: Record<string, unknown> = {
  type: "object",
  additionalProperties: true,
  required: [...ticketRequired, "ticket_comments"],
  properties: {
    ...ticketRowProperties,
    created_by: { type: "string" },
    ticket_comments: { type: "array", items: ticketCommentSchema },
  },
};

